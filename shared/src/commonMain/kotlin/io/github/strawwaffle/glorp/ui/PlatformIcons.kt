    private val other = Mark("Video", Palette.TextDim, "M8,5v14l11,-7z")

    /** `twitch-vod` and `kick-vod` are the same platform as `twitch` and `kick`. */
    private fun markOf(platform: String) = marks[platform.substringBefore('-').lowercase()]

    /** The platform's name as it writes it: "Twitch", "YouTube"; unknown ones as given. */
    fun name(platform: String): String = markOf(platform)?.name ?: platform.substringBefore('-').replaceFirstChar { it.uppercase() }

    internal fun vectorOf(platform: String): Pair<ImageVector, Color> = (markOf(platform) ?: other).let { it.vector to it.color }
}

/** [platform]'s mark in its colour, named for screen readers. */
@Composable
internal fun PlatformIcon(platform: String, size: Dp = 18.dp, modifier: Modifier = Modifier) {
    val (vector, color) = PlatformIcons.vectorOf(platform)
    Icon(vector, contentDescription = PlatformIcons.name(platform), tint = color, modifier = modifier.size(size))
}
